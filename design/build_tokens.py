"""Generate static/src/tokens.css from design/lumen/tokens.json.

The Lumen design system (design/lumen/README.md) is the source of truth for
colour, type, spacing, corner radius, component heights, borders, shadows and
icon sizes. This turns it into CSS custom properties — `:root` for the light
theme, `.dark` for the dark one — which tailwind.config.js and
static/src/input.css consume. Run it after editing tokens.json:

    python design/build_tokens.py && npm run build:css

Colour values may alias another token (`"{gray-800}"`); aliases are resolved
per theme, so `content-default` is gray-800 of the light palette in light and
gray-800 of the dark palette in dark. Every opaque colour is also written as an
`-rgb` channel triple so Tailwind's opacity modifiers (`bg-accent-background/10`)
keep working.
"""

import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent
tokens = json.loads((ROOT / "lumen" / "tokens.json").read_text())
OUT = ROOT.parent / "static" / "src" / "tokens.css"
THEMES = [theme["id"] for theme in tokens["color"]["themes"]]
COLORS = {token["name"]: token["value"] for token in tokens["color"]["tokens"]}
ALIAS = re.compile(r"^\{([A-Za-z0-9_.-]+)\}$")


def themed(value, theme):
    """A token's value in one theme; a missing theme inherits the first one's."""
    if isinstance(value, str):
        return value
    return value.get(theme, value[THEMES[0]])


def resolve(name, theme, seen=()):
    value = themed(COLORS[name], theme)
    match = ALIAS.match(value)
    if not match:
        return value
    target = match.group(1)
    if target in seen or target not in COLORS:
        raise ValueError(f"bad alias {value} in {name}")
    return resolve(target, theme, (*seen, name))


def rgb_channels(value):
    """`#rrggbb` -> `r g b`; None for anything with alpha or not hex."""
    value = value.lstrip("#")
    if len(value) == 3:
        value = "".join(ch * 2 for ch in value)
    if not re.fullmatch(r"[0-9a-fA-F]{6}", value):
        return None
    return " ".join(str(int(value[i : i + 2], 16)) for i in (0, 2, 4))


def block(selector, theme, extras):
    lines = [f"{selector} {{"]
    for name in COLORS:
        value = resolve(name, theme)
        lines.append(f"  --{name}: {value};")
        channels = rgb_channels(value)
        if channels:
            lines.append(f"  --{name}-rgb: {channels};")
    for token in tokens["shadow"]["tokens"]:
        lines.append(f"  --{token['name']}: {themed(token['value'], theme)};")
    lines += extras
    lines.append("}")
    return "\n".join(lines)


shared = []
for family in ("spacing", "radius", "height", "border", "icon"):
    for token in tokens[family]["tokens"]:
        shared.append(f"  --{token['name']}: {token['value']};")
for name, stack in tokens["type"]["families"].items():
    shared.append(f"  --font-{name}: {stack};")

css = "\n".join(
    [
        "/* GENERATED by design/build_tokens.py from design/lumen/tokens.json — do not edit. */",
        block(":root", THEMES[0], ["  color-scheme: light;", *shared]),
        "",
        block(".dark", THEMES[1], ["  color-scheme: dark;"]),
        "",
    ]
)
OUT.write_text(css)
print(f"wrote {OUT.relative_to(ROOT.parent)} ({len(COLORS)} colours, themes: {', '.join(THEMES)})")
